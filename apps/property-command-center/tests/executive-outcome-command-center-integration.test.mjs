import assert from 'node:assert/strict';
import {createExecutiveOutcomeViewModel,buildExecutiveOutcomeReviewQueue,createExecutiveOutcomeLineage,createExecutiveOutcomeCommandCenterAdapter} from '../src/executive-actions/command-center/index.js';
let testsRun=0;const test=(n,f)=>{f();testsRun++;};
const complete={outcomeId:'OUTCOME:WF-1',workflowRequestId:'WF-1',workflowId:'ENGINE-1',proposalId:'PROP-1',approvalId:'APR-1',sourceSignalIds:['SIG-1'],classification:'COMPLETED',durationMs:300000,evidenceCount:1,completedAt:'2026-07-31T17:00:00.000Z'};
const failed={...complete,outcomeId:'OUTCOME:WF-2',workflowRequestId:'WF-2',classification:'FAILED',requiresReview:true,completedAt:'2026-07-31T18:00:00.000Z'};
const vm=createExecutiveOutcomeViewModel(complete);
test('view model id',()=>assert.equal(vm.id,'OUTCOME:WF-1'));
test('view model immutable',()=>assert.equal(Object.isFrozen(vm),true));
test('completed severity',()=>assert.equal(vm.severity,'INFO'));
test('read only',()=>assert.equal(vm.workflowMutationAllowed,false));
test('autonomy disabled',()=>assert.equal(vm.autonomousExecutionAllowed,false));
test('traceability enabled',()=>assert.equal(vm.decisionTraceability,true));
const failedVm=createExecutiveOutcomeViewModel(failed);
test('failed review required',()=>assert.equal(failedVm.requiresReview,true));
test('failed attention severity',()=>assert.equal(failedVm.severity,'ATTENTION'));
const queue=buildExecutiveOutcomeReviewQueue([vm,failedVm]);
test('review queue count',()=>assert.equal(queue.length,1));
test('review status',()=>assert.equal(queue[0].reviewStatus,'PENDING_HUMAN_REVIEW'));
test('review rank',()=>assert.equal(queue[0].reviewRank,1));
const lineage=createExecutiveOutcomeLineage(vm);
test('lineage complete',()=>assert.equal(lineage.complete,true));
test('lineage immutable',()=>assert.equal(lineage.immutable,true));
test('source signal retained',()=>assert.deepEqual(lineage.sourceSignalIds,['SIG-1']));
const adapter=createExecutiveOutcomeCommandCenterAdapter({maxItems:2});
test('adapter ready',()=>assert.equal(adapter.snapshot().status,'READY'));
test('adapter start',()=>assert.equal(adapter.start().status,'OPERATIONAL'));
const first=adapter.ingest(complete);
test('ingest success',()=>assert.equal(first.status,'INGESTED'));
test('duplicate suppression',()=>assert.equal(adapter.ingest(complete).status,'DUPLICATE_IGNORED'));
test('failed ingest',()=>assert.equal(adapter.ingest(failed).status,'INGESTED'));
const dashboard=adapter.getDashboardModel();
test('dashboard total',()=>assert.equal(dashboard.totalOutcomes,2));
test('dashboard review count',()=>assert.equal(dashboard.reviewRequired,1));
test('dashboard success rate',()=>assert.equal(dashboard.successRatePct,50));
test('dashboard readonly',()=>assert.equal(dashboard.readOnly,true));
test('stop lifecycle',()=>assert.equal(adapter.stop().status,'STOPPED'));
const snap=adapter.snapshot('STOPPED');
console.log(JSON.stringify({framework:'SCIIP_PHASE2_SPRINT5_EXECUTIVE_OUTCOME_COMMAND_CENTER_INTEGRATION',status:'PASSED',testsRun,result:{status:'STOPPED',outcomesIngested:snap.ingested,retainedItems:snap.retainedItems,duplicatesIgnored:snap.duplicatesIgnored,reviewQueueItems:adapter.getReviewQueue().length,successRatePct:dashboard.successRatePct,readOnly:snap.readOnly,workflowMutationAllowed:snap.workflowMutationAllowed,autonomousExecutionAllowed:snap.autonomousExecutionAllowed,decisionTraceability:snap.decisionTraceability}},null,2));
