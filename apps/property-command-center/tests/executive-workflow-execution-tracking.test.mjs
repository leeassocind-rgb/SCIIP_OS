import assert from 'node:assert/strict';
import { createExecutiveWorkflowExecutionTracker, createExecutiveWorkflowExecutionSnapshot, createExecutiveExecutionEvidence, reconstructExecutiveExecutionTimeline, executionDurationMs } from '../src/executive-actions/execution/index.js';
let testsRun=0; const test=(name,fn)=>{fn();testsRun++;};
const base={workflowRequestId:'WF-100',workflowId:'ENGINE-100',proposalId:'PROP-100',approvalId:'APR-100',sourceSignalIds:['SIG-100']};
const tracker=createExecutiveWorkflowExecutionTracker({maxEvents:4});
test('snapshot factory',()=>assert.equal(createExecutiveWorkflowExecutionSnapshot({...base,status:'ACCEPTED'}).status,'ACCEPTED'));
test('evidence factory',()=>assert.equal(createExecutiveExecutionEvidence({workflowRequestId:'WF-100',type:'DOCUMENT',uri:'memory://a'}).type,'DOCUMENT'));
test('ready state',()=>assert.equal(tracker.snapshot().status,'READY'));
test('start lifecycle',()=>assert.equal(tracker.start().status,'OPERATIONAL'));
const accepted=tracker.accept({...base,eventId:'E1',occurredAt:'2026-07-31T15:00:00.000Z'});
test('accept workflow',()=>assert.equal(accepted.status,'ACCEPTED'));
test('immutable snapshot',()=>assert.equal(Object.isFrozen(accepted),true));
const bad=tracker.complete({...base,eventId:'E-BAD'});
test('invalid transition blocked',()=>assert.equal(bad.status,'INVALID_TRANSITION_BLOCKED'));
const running=tracker.startExecution({...base,eventId:'E2',actorId:'USER-1',occurredAt:'2026-07-31T15:01:00.000Z'});
test('start execution',()=>assert.equal(running.status,'RUNNING'));
const duplicate=tracker.startExecution({...base,eventId:'E2'});
test('duplicate suppression',()=>assert.equal(duplicate.status,'DUPLICATE_IGNORED'));
const ev=tracker.attachEvidence({workflowRequestId:'WF-100',evidenceId:'EV-1',type:'REPORT',uri:'memory://report',checksum:'abc'});
test('evidence attachment',()=>assert.equal(ev.evidenceId,'EV-1'));
const paused=tracker.pause({...base,eventId:'E3',occurredAt:'2026-07-31T15:02:00.000Z'});
test('pause tracking',()=>assert.equal(paused.status,'PAUSED'));
const resumed=tracker.resume({...base,eventId:'E4',evidenceIds:['EV-1'],occurredAt:'2026-07-31T15:03:00.000Z'});
test('resume tracking',()=>assert.equal(resumed.status,'RUNNING'));
const completed=tracker.complete({...base,eventId:'E5',evidenceIds:['EV-1'],occurredAt:'2026-07-31T15:05:00.000Z'});
test('completion tracking',()=>assert.equal(completed.terminal,true));
test('terminal mutation blocked',()=>assert.equal(tracker.fail({...base,eventId:'E6'}).status,'INVALID_TRANSITION_BLOCKED'));
const timeline=tracker.getTimeline('WF-100');
test('bounded history',()=>assert.equal(timeline.length,4));
test('timeline ordering',()=>assert.deepEqual(timeline.map(x=>x.sequence),[2,3,4,5]));
test('timeline evidence reconstruction',()=>assert.equal(timeline.at(-1).evidence[0].evidenceId,'EV-1'));
test('duration metrics',()=>assert.equal(executionDurationMs(timeline),240000));
const summary=tracker.getExecutionSummary('WF-100');
test('traceability',()=>assert.deepEqual(summary.sourceSignalIds,['SIG-100']));
test('stop lifecycle',()=>assert.equal(tracker.stop().status,'STOPPED'));
const snap=tracker.snapshot();
console.log(JSON.stringify({framework:'SCIIP_PHASE2_SPRINT3_GOVERNED_WORKFLOW_EXECUTION_TRACKING',status:'PASSED',testsRun,result:{status:'STOPPED',trackedWorkflows:snap.trackedWorkflows,eventsRecorded:snap.eventsRecorded,retainedEvents:snap.retainedEvents,duplicatesIgnored:snap.duplicatesIgnored,invalidTransitionsBlocked:snap.invalidTransitionsBlocked,evidenceAttached:snap.evidenceAttached,failures:snap.failures,workflowStatus:summary.status,immutableHistory:snap.immutableHistory,decisionTraceability:true,autonomousExecutionAllowed:snap.autonomousExecutionAllowed}},null,2));
